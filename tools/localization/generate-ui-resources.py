#!/usr/bin/env python3
"""Generate Android strings and the typed English-label lookup from UTF-8 TSV."""
import csv,re,xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape
ROOT=Path(__file__).resolve().parents[2]
LANGUAGES=('en','es','pt','fr','de','ja','pl')
source=ROOT/'tools/localization/strings.tsv'
rows=list(csv.reader(source.open(encoding='utf-8'),delimiter='\t'))
assert all(len(row)==7 and all(row) for row in rows)
assert len({r[0] for r in rows})==len(rows)
base=ROOT/'app/src/main/res/values/strings.xml'
existing={n.text.replace("\\'", "'"):n.attrib['name'] for n in ET.parse(base).getroot() if not n.attrib['name'].startswith('ui_')}
existing['Debian Noroot']='app_name'
if 'Debian Noroot' not in {r[0] for r in rows}:rows.append(['Debian Noroot']*7)
assert not set(existing)-{r[0] for r in rows},set(existing)-{r[0] for r in rows}
ids={r[0]:existing.get(r[0],'ui_'+re.sub('[^a-z0-9]+','_',r[0].lower().replace('%',' percent ').replace('…',' ellipsis ')).strip('_')) for r in rows}
assert len(set(ids.values()))==len(ids)
def android(s):return escape(s.replace('\\','\\\\').replace("'","\\'").replace('"','\\"'))
for i,language in enumerate(LANGUAGES):
 folder=ROOT/'app/src/main/res'/('values' if language=='en' else 'values-'+language);folder.mkdir(exist_ok=True)
 (folder/'strings.xml').write_text('<resources>\n'+''.join(f'    <string name="{ids[r[0]]}">{android(r[i])}</string>\n' for r in rows)+'</resources>\n',encoding='utf-8')
def java(s):return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
text='''package org.debiannoroot.settings;
import org.debiannoroot.R;
import android.content.Context;
/** Generated by tools/localization/generate-ui-resources.py; edit tools/localization/strings.tsv. */
public final class UiText {
    private UiText(){}
    public static String get(Context context,String source){
        if(source==null)return "";
        switch(source){
'''
for english in ids:text+=f'            case {java(english)}: return context.getString(R.string.{ids[english]});\n'
text+='            default:return source;\n        }\n    }\n}\n'
(ROOT/'app/src/main/java/org/debiannoroot/settings/UiText.java').write_text(text,encoding='utf-8')
print(f'Generated {len(rows)} strings in {len(LANGUAGES)} languages')
